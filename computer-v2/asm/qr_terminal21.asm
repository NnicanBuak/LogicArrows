; Адрес байта шаблона = template + 3 * Y + (X >> 3).
; В служебных областях шаблон задаёт готовый узор.
; В областях данных шаблон задаёт маску 0: чёрный при (X + Y) % 2 = 0.
fixed_bit:              ld a, Y
                        mov b, a
                        shl a
                        add b, a
                        ld a, X
                        mov c, a
                        shr c
                        shr c
                        shr c
                        add b, c
                        ldi c, template
                        add b, c
                        ld a, b
                        ld b, X
                        ldi c, 7
                        and b, c
                        inc b

; Извлечь бит шаблона, выполнить XOR с pixeldata и вернуть цвет в A.
extract_fixed:          shl a
                        dec b
                        jnz extract_fixed
                        clr a
                        rcl a
                        ld b, pixeldata
                        xor a, b
                        jmp pixel_done

